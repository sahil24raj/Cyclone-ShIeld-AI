export class IBTrACSService {
  /**
   * Retrieves all verified NOAA IBTrACS historical storms.
   */
  public static getAllHistoricalStorms(): IBTrACSStormEvent[] {
    return NOAA_IBTRACS_NI_BENCHMARK;
  }

  /**
   * Finds a specific storm by ID or Name.
   */
  public static getStormByIdOrName(query: string): IBTrACSStormEvent | undefined {
    const q = query.trim().toUpperCase();
    return NOAA_IBTRACS_NI_BENCHMARK.find(
      (s) => s.stormId.toUpperCase() === q || s.stormName.toUpperCase() === q
    );
  }

  /**
   * Filters storms by minimum peak wind speed.
   */
  public static getStormsByMinWind(minWindKmh: number): IBTrACSStormEvent[] {
    return NOAA_IBTRACS_NI_BENCHMARK.filter((s) => s.peakWindKmh >= minWindKmh);
  }

  /**
   * Returns dataset provenance metadata for UI transparency.
   */
  public static getDatasetProvenance() {
    return {
      name: 'NOAA IBTrACS North Indian Ocean Historical Archive',
      agency: 'NOAA National Centers for Environmental Information (NCEI)',
      datasetVersion: 'v04r00',
      officialUrl: 'https://www.ncei.noaa.gov/products/international-best-track-archive',
      dataMode: 'HISTORICAL' as const,
      purpose: 'Historical benchmark analysis, ML risk calibration, and validation baseline.',
      citation: 'Knapp, K. R., et al. (2018). The International Best Track Archive for Climate Stewardship (IBTrACS). NOAA NCEI.',
    };
  }
}
